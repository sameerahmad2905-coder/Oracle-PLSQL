🔹 1. EXPLICIT CURSOR + FETCH LOOP (ROW-BY-ROW / SLOWEST) --> USUAL CURSOR PERFORMS LIKE

HERE WE FETCH ONE ROW AT A TIME, THEN UPDATE.

DECLARE
   CURSOR EMP_CUR IS
       SELECT EMPNO, SAL FROM EMP WHERE DEPTNO = 20;

   V_EMPNO EMP.EMPNO%TYPE;
   V_SAL   EMP.SAL%TYPE;
BEGIN
   OPEN EMP_CUR;
   LOOP
      FETCH EMP_CUR INTO V_EMPNO, V_SAL;
      EXIT WHEN EMP_CUR%NOTFOUND;

      UPDATE EMP
      SET SAL = V_SAL * 1.10
      WHERE EMPNO = V_EMPNO;
   END LOOP;
   CLOSE EMP_CUR;

   COMMIT;
END;
/
⚡ PROS: SIMPLE, EASY TO UNDERSTAND.
⚡ CONS: SLOW FOR LARGE DATA (ROW-BY-ROW = SLOW-BY-SLOW).



🔹 2. EXPLICIT CURSOR FOR UPDATE (CLEANER ROW-BY-ROW)  --> EXPLICIT CURSOR FOR UPDATE MEANS AVOIDING THE BOLF OPERATIONS

HERE ORACLE AUTOMATICALLY LOCKS ROWS, AND WE USE WHERE CURRENT OF.

DECLARE
   CURSOR EMP_CUR IS
       SELECT EMPNO, SAL FROM EMP WHERE DEPTNO = 20
       FOR UPDATE OF SAL NOWAIT;

BEGIN
   FOR REC IN EMP_CUR LOOP
      UPDATE EMP
      SET SAL = REC.SAL * 1.10
      WHERE CURRENT OF EMP_CUR;
   END LOOP;

   COMMIT;
END;
/
⚡ PROS: CLEANER, NO NEED TO CARRY PRIMARY KEY MANUALLY, SAFE ROW LOCKS.
⚡ CONS: STILL ROW-BY-ROW (SLOW FOR BIG TABLES).



🔹 3. SET-BASED DML (BEST PRACTICE FOR BULK UPDATE)

HERE WE DON’T NEED A CURSOR AT ALL. ONE SQL STATEMENT DOES THE JOB.

BEGIN
   UPDATE EMP
   SET SAL = SAL * 1.10
   WHERE DEPTNO = 20;

   COMMIT;
END;
/
⚡ PROS: FASTEST (ORACLE’S SQL ENGINE HANDLES EVERYTHING).
⚡ CONS: NOT FLEXIBLE IF YOU NEED ROW-BY-ROW LOGIC (E.G., COMPLEX CALCULATIONS OR LOGGING).



🔹 4. COLLECTIONS + FORALL (BULK DML, MIDDLE GROUND)

	IF YOU NEED ROW-BY-ROW LOGIC BUT FASTER THAN CURSOR, USE COLLECTIONS.

