A CURSOR IS A POINTER TO A RESULT SET RETURNED BY A SQL QUERY. IT ALLOWS PL/SQL TO FETCH ROWS ONE-BY-ONE (OR IN BULK) FROM THE QUERY RESULT.

TYPES OF CURSORS
🔆🔆🔆🔆🔆🔆🔆🔆🔆🔆🔆

IMPLICIT CURSOR → CREATED AUTOMATICALLY BY ORACLE WHEN A DML/SELECT INTO IS EXECUTED.
EXPLICIT CURSOR → DECLARED BY PROGRAMMER TO PROCESS MULTIPLE ROWS FROM A QUERY.

CURSOR VARIABLES (REF CURSORS) → POINTERS TO QUERIES, USEFUL FOR DYNAMIC SQL OR RETURNING QUERY RESULTS FROM PROCEDURES/FUNCTIONS.

🔆 KEY USES

TO PROCESS QUERY RESULTS ROW BY ROW.
TO HANDLE MULTI-ROW SELECT STATEMENTS IN PL/SQL.
USEFUL FOR REPORTING, VALIDATIONS, OR BUSINESS LOGIC REQUIRING ROW-LEVEL PROCESSING.

🔹 LIFE CYCLE OF AN EXPLICIT CURSOR

DECLARE THE CURSOR – DEFINE SQL STATEMENT.
OPEN THE CURSOR – ALLOCATE MEMORY AND EXECUTE QUERY.
FETCH ROWS – RETRIEVE ROWS ONE AT A TIME.
CLOSE THE CURSOR – RELEASE MEMORY.



🔹 SYNTAX
DECLARE
   CURSOR CURSOR_NAME IS
       SELECT COLUMN_LIST FROM TABLE_NAME WHERE CONDITION;
   VAR1 TABLE.COLUMN1%TYPE;										   -- VARIABLES TO HOLD FETCHED VALUES
   VAR2 TABLE.COLUMN2%TYPE;
BEGIN
   OPEN CURSOR_NAME;
   LOOP
      FETCH CURSOR_NAME INTO VAR1, VAR2;
      EXIT WHEN CURSOR_NAME%NOTFOUND;   -- EXIT WHEN NO MORE ROWS
      DBMS_OUTPUT.PUT_LINE(VALUE:  || VAR1 || ,  || VAR2);			      -- PROCESS THE ROW
   END LOOP;
   CLOSE CURSOR_NAME;
END;
/


