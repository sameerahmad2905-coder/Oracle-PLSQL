20. What is a Cursor? Why is it Required?
🔆A cursor is a temporary work area that is created in system memory when an SQL statement is executed. 
🔆A cursor contains information on a select statement and the row of data accessed by it. 
🔆This temporary work area stores the data, which is retrieved from the database, to manipulate it. 
🔆A cursor can hold more than one row but can process only one row at a time. 
🔆A cursor is required to process rows individually for queries.

21. What are the Types of Cursors?
There are two types of cursors:

IMPLICIT CURSOR: An implicit cursor in Oracle is a cursor that Oracle automatically creates and manages when we execute a SQL statement (like SELECT, INSERT, UPDATE, or DELETE). 
We dont need to declare, open, fetch from, or close it explicitly - Oracle handles all of that behind the scenes.
INSERT
UPDATE
DELETE
SELECT

Key Characteristics
When we execute a DML statement or a SELECT INTO query, Oracle automatically creates an implicit cursor to process the SQL statement and store the result temporarily.

Implicit Cursor Attributes
Oracle provides attributes to check the status of the most recently executed SQL statement:

SQL%FOUND - Returns TRUE if the SQL statement affected one or more rows
SQL%NOTFOUND - Returns TRUE if no rows were affected
SQL%ROWCOUNT - Returns the number of rows affected by the SQL statement
SQL%ISOPEN - Always returns FALSE for implicit cursors (they close automatically after execution)

