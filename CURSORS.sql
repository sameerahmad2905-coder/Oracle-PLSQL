DECLARE
CURSOR CUR_EMP IS SELECT EMPNO, ENAME, DEPTNO, MGR_ID  FROM EMP WHERE SAL < 7000;
V_ID EMP.EMPNO%TYPE;
V_NAME EMP.ENAME%TYPE;
V_DEP EMP.DEPTNO%TYPE;
V_MGR EMP.MGR_ID%TYPE;
V_COUNT NUMBER;
BEGIN
OPEN CUR_EMP;
LOOP
FETCH CUR_EMP INTO V_ID, V_NAME, V_DEP, V_MGR;
EXIT WHEN CUR_EMP%NOTFOUND;
DBMS_OUTPUT.PUT_LINE(V_ID||', '||V_NAME||', '||V_DEP||', '||V_MGR);
END LOOP;
V_COUNT := CUR_EMP%ROWCOUNT;
DBMS_OUTPUT.PUT_LINE(V_COUNT);
END;
/

