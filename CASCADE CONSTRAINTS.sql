🔹 WHAT IS CASCADE IN ORACLE CONSTRAINTS?

WHEN YOU DROP OR MODIFY A TABLE IN ORACLE, YOU MAY ENCOUNTER CONSTRAINTS LIKE -
FOREIGN KEYS THAT DEPEND ON IT.

ORACLE WON’T LET YOU DROP A TABLE OR A PRIMARY KEY IF CHILD TABLES (FOREIGN KEYS) STILL REFERENCE IT… UNLESS YOU USE CASCADE CONSTRAINTS.

🔹 SYNTAX
DROP TABLE PARENT_TABLE CASCADE CONSTRAINTS;


OR WHEN DROPPING A PRIMARY KEY:

ALTER TABLE PARENT_TABLE DROP PRIMARY KEY CASCADE;

🔹 EXAMPLE 1: DROPPING A TABLE WITH CHILD REFERENCES

SUPPOSE WE HAVE:

CREATE TABLE DEPT (
   DEPT_ID NUMBER PRIMARY KEY,
   DEPT_NAME VARCHAR2(50)
);

CREATE TABLE EMP (
   EMP_ID NUMBER PRIMARY KEY,
   EMP_NAME VARCHAR2(50),
   DEPT_ID NUMBER REFERENCES DEPT(DEPT_ID)
);


NOW, IF WE TRY:

DROP TABLE DEPT;


❌ ORACLE WILL THROW AN ERROR:
ORA-02449: UNIQUE/PRIMARY KEYS IN TABLE REFERENCED BY FOREIGN KEYS

✅ CORRECT WAY:

DROP TABLE DEPT CASCADE CONSTRAINTS;


👉 THIS WILL DROP THE DEPT TABLE AND ALSO REMOVE ALL FOREIGN KEY CONSTRAINTS IN CHILD TABLES (HERE, EMP.DEPT_ID).

🔹 EXAMPLE 2: DROPPING A PRIMARY KEY WITH CASCADE
ALTER TABLE DEPT DROP PRIMARY KEY CASCADE;


👉 THIS WILL DROP THE PRIMARY KEY IN DEPT AND ALSO REMOVE ANY FOREIGN KEY CONSTRAINTS IN CHILD TABLES (EMP).

⚠️ IMPORTANT NOTES

CASCADE CONSTRAINTS DOES NOT DROP THE CHILD TABLE.
IT ONLY REMOVES THE CONSTRAINTS THAT REFERENCE THE PARENT. THE CHILD TABLE REMAINS INTACT, BUT ITS FOREIGN KEY CONSTRAINT DISAPPEARS.

IF YOU WANT TO DROP THE PARENT AND CHILD TABLES TOGETHER, YOU MUST EXPLICITLY DROP BOTH TABLES.

✅ SUMMARY

CASCADE CONSTRAINTS IS USED WHEN DROPPING TABLES OR PRIMARY KEYS THAT ARE REFERENCED BY FOREIGN KEYS.

IT ENSURES REFERENTIAL INTEGRITY CONSTRAINTS ARE AUTOMATICALLY REMOVED.

IT DOES NOT DELETE CHILD TABLES OR DATA — ONLY THE CONSTRAINTS.

