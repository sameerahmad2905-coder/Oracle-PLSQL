DECLARE
TYPE TBL_EMP IS TABLE OF EMP_TEST%ROWTYPE INDEX BY PLS_INTEGER;
VAR_EMP TBL_EMP;

null_val_ins EXCEPTION;
PRAGMA EXCEPTION_INIT(null_val_ins, -01400);

uniq_cons_viol EXCEPTION;
PRAGMA EXCEPTION_INIT(uniq_cons_viol, -00001);

  l_error_count  NUMBER;

BEGIN

SELECT * BULK COLLECT INTO VAR_EMP FROM EMP_TEST WHERE DEPARTMENT_ID=50;

FORALL I IN VAR_EMP.FIRST..VAR_EMP.LAST SAVE EXCEPTIONS
INSERT INTO EMPP (EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, DEPARTMENT_ID) VALUES 
        (VAR_EMP(I).EMPLOYEE_ID, VAR_EMP(I).FIRST_NAME, VAR_EMP(I).LAST_NAME, VAR_EMP(I).SALARY, VAR_EMP(I).DEPARTMENT_ID);

EXCEPTION
WHEN null_val_ins THEN
  l_error_count  := SQL%BULK_EXCEPTIONS.COUNT;
  DBMS_OUTPUT.PUT_LINE('FAILURES '||l_error_count);

WHEN  uniq_cons_viol THEN  
	 l_error_count  := SQL%BULK_EXCEPTIONS.COUNT;
  DBMS_OUTPUT.PUT_LINE('UNIQUE CONSTRAINT ERROR COUNT - '||l_error_count);
  
  FOR I IN l_error_count LOOP
			DBMS_OUTPUT.PUT_LINE('ERROR '||I||' Array Index '||SQL%BULK_EXCEPTIONS(I).ERROR_INDEX ||    ' MESSAGE '||SQLERRM(-SQL%BULK_EXCEPTIONS(I).ERROR_CODE));
   END LOOP;
END;
/
  

