-----------------------------SAVE EXCEPTIONS-------------
---------------------------------------------------------

GREAT QUESTION 👍 — YOU’RE ASKING ABOUT SAVE EXCEPTIONS WITH COLLECTIONS IN ORACLE PL/SQL, WHICH IS A VERY USEFUL FEATURE FOR BULK DML (INSERT/UPDATE/DELETE).

LET ME EXPLAIN IN DETAIL WITH EXAMPLES.

🔹 WHAT IS SAVE EXCEPTIONS?

WHEN YOU USE FORALL WITH COLLECTIONS TO PERFORM BULK DML, IF ANY STATEMENT FAILS, BY DEFAULT THE ENTIRE OPERATION STOPS AND THROWS AN ERROR.

👉 BUT WITH SAVE EXCEPTIONS, ORACLE CONTINUES PROCESSING THE REST OF THE ROWS, AND AT THE END, RAISES AN EXCEPTION ORA-24381: ERROR(S) IN ARRAY DML.

YOU CAN THEN CHECK WHICH ROWS FAILED USING THE SPECIAL COLLECTION SQL%BULK_EXCEPTIONS.

🔹 SYNTAX OF FORALL WITH SAVE EXCEPTIONS
FORALL INDEX IN COLLECTION.FIRST .. COLLECTION.LAST SAVE EXCEPTIONS
   DML_STATEMENT;

🔹 EXAMPLE 1: BULK INSERT WITH SAVE EXCEPTIONS

DECLARE
  TYPE T_EMPNO IS TABLE OF EMP.EMPNO%TYPE;
  V_EMPNOS T_EMPNO := T_EMPNO(7369, 7499, 9999, 7521); -- 9999 DOESN'T EXIST IN EMP
BEGIN
  FORALL I IN V_EMPNOS.FIRST .. V_EMPNOS.LAST SAVE EXCEPTIONS
    INSERT INTO BONUS (EMPNO, JOB, SAL, COMM)
    SELECT EMPNO, JOB, SAL, COMM
    FROM EMP
    WHERE EMPNO = V_EMPNOS(I);
  DBMS_OUTPUT.PUT_LINE('ALL ROWS INSERTED SUCCESSFULLY!');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR COUNT: ' || SQL%BULK_EXCEPTIONS.COUNT);
    FOR I IN 1 .. SQL%BULK_EXCEPTIONS.COUNT	LOOP
    DBMS_OUTPUT.PUT_LINE('ERROR AT ITERATION ' || SQL%BULK_EXCEPTIONS(I).ERROR_INDEX ||  ' -> ORACLE ERROR: ' || SQL%BULK_EXCEPTIONS(I).ERROR_CODE );
    END LOOP;
END;
/

🔹 OUTPUT (EXAMPLE)
ERROR COUNT: 1
ERROR AT ITERATION 3 -> ORACLE ERROR: 1403


👉 THIS MEANS THE 3RD RECORD (9999) CAUSED AN ERROR (NO DATA FOUND), BUT OTHERS WERE INSERTED SUCCESSFULLY.

🔹 EXAMPLE 2: BULK UPDATE WITH SAVE EXCEPTIONS
DECLARE
  TYPE T_SAL IS TABLE OF EMP.SAL%TYPE;
  TYPE T_EMPNO IS TABLE OF EMP.EMPNO%TYPE;

  V_SALS   T_SAL   := T_SAL(3000, 5000, 4000);
  V_EMPNOS T_EMPNO := T_EMPNO(7369, 7499, 9999); -- 9999 DOESN’T EXIST
BEGIN
  FORALL I IN V_EMPNOS.FIRST .. V_EMPNOS.LAST SAVE EXCEPTIONS
    UPDATE EMP
    SET SAL = V_SALS(I)
    WHERE EMPNO = V_EMPNOS(I);

  DBMS_OUTPUT.PUT_LINE('BULK UPDATE COMPLETED!');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERRORS: ' || SQL%BULK_EXCEPTIONS.COUNT);
    FOR J IN 1 .. SQL%BULK_EXCEPTIONS.COUNT LOOP
      DBMS_OUTPUT.PUT_LINE(
        'ROW ' || SQL%BULK_EXCEPTIONS(J).ERROR_INDEX ||
        ' FAILED WITH ERROR CODE ' || SQL%BULK_EXCEPTIONS(J).ERROR_CODE
      );
    END LOOP;
END;
/


👉 HERE ALSO, ROW WITH EMPNO 9999 WILL FAIL, BUT OTHERS WILL SUCCEED.

🔹 KEY POINTS ABOUT SAVE EXCEPTIONS

WITHOUT SAVE EXCEPTIONS → FIRST ERROR STOPS ENTIRE BATCH.

WITH SAVE EXCEPTIONS → EXECUTION CONTINUES FOR ALL ROWS, AND ERRORS ARE COLLECTED IN SQL%BULK_EXCEPTIONS.

SQL%BULK_EXCEPTIONS IS AN ASSOCIATIVE ARRAY OF RECORDS WITH FIELDS:

ERROR_INDEX → WHICH COLLECTION ELEMENT FAILED.

ERROR_CODE → ORACLE ERROR CODE (LIKE -1403, -1, ETC.).

YOU MUST HANDLE EXCEPTIONS AFTER THE FORALL BLOCK.

✅ IN SHORT:
SAVE EXCEPTIONS IS EXTREMELY USEFUL WHEN YOU WANT MAXIMUM SUCCESSFUL OPERATIONS IN BULK DML, WHILE STILL KEEPING TRACK OF WHICH RECORDS FAILED.

DO YOU WANT ME TO ALSO SHOW YOU A REAL-TIME USE CASE (LIKE INSERTING THOUSANDS OF ROWS WHERE SOME VIOLATE UNIQUE CONSTRAINT) TO SEE HOW SAVE EXCEPTIONS HELPS IN PRODUCTION?

ORA-00001 → Unique constraint violated
ORA-01403 → No data found
ORA-02292 → Child record found

