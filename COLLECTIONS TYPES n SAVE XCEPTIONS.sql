COLLECTIONS IN ORACLE PL/SQL

A COLLECTION IS A DATA STRUCTURE THAT CAN HOLD MULTIPLE VALUES IN MEMORY (LIKE ARRAYS IN PROGRAMMING).
TYPES OF COLLECTIONS IN PL/SQL:

ASSOCIATIVE ARRAYS (INDEX-BY TABLES) → KEY-VALUE PAIRS.

NESTED TABLES → UNORDERED SETS THAT CAN BE STORED IN DB COLUMNS.

VARRAYS (VARIABLE-SIZE ARRAYS) → FIXED MAXIMUM SIZE, ORDERED ARRAYS.

KEY USES

TO STORE AND PROCESS MULTIPLE VALUES IN MEMORY (NOT TIED TO A QUERY RESULT).

FOR BULK PROCESSING (USING BULK COLLECT AND FORALL FOR HIGH PERFORMANCE).

FOR PASSING LISTS OF VALUES TO PROCEDURES/FUNCTIONS.

EXAMPLE 2: COLLECTION WITH BULK COLLECT
DECLARE
  TYPE T_EMP IS TABLE OF EMP.ENAME%TYPE;
  V_EMP T_EMP;
BEGIN
  SELECT ENAME 
  BULK COLLECT INTO V_EMP
  FROM EMP
  WHERE DEPTNO = 10;

  FOR I IN 1 .. V_EMP.COUNT LOOP
    DBMS_OUTPUT.PUT_LINE(V_EMP(I));
  END LOOP;
END;
/



🧩 Technical Difference
Cursor
Pointer to SQL result set
Fetches row-by-row
Lives between SQL and PL/SQL engine

Collection
PL/SQL memory structure
Stores multiple values
Used for bulk collect & FORALL

👉 HERE, INSTEAD OF FETCHING ROW BY ROW (LIKE CURSORS), WE FETCHED ALL NAMES AT ONCE INTO MEMORY.


🔹 CURSOR VS COLLECTION: KEY DIFFERENCES
FEATURE							CURSOR										COLLECTION
DEFINITION			POINTER TO RESULT SET FROM SQL QUERY		IN-MEMORY DATA STRUCTURE (LIKE ARRAY/LIST)
SCOPE				TIED TO A SQL QUERY EXECUTION				INDEPENDENT OF QUERIES, BUT CAN BE POPULATED BY THEM
PROCESSING STYLE	ROW-BY-ROW (CAN USE BULK FETCH)				SET-BASED (CAN STORE ALL ROWS AT ONCE)
TYPES				IMPLICIT, EXPLICIT, REF CURSOR				ASSOCIATIVE ARRAY, NESTED TABLE, VARRAY
DATA SOURCE			ALWAYS COMES FROM SQL QUERY					CAN BE POPULATED FROM QUERIES, CONSTANTS, OR COMPUTED VALUES
PERFORMANCE			ROW-BY-ROW (SLOWER UNLESS BULK FETCH USED)	HIGH PERFORMANCE WITH BULK COLLECT & FORALL
STORAGE IN DB		CANNOT BE STORED DIRECTLY IN A TABLE		NESTED TABLES AND VARRAYS CAN BE STORED AS TABLE COLUMNS
USE CASE			ITERATING THROUGH QUERY RESULTS, 			TEMPORARY IN-MEMORY STORAGE, BULK OPERATIONS, LIST PASSING, 
					DYNAMIC QUERIES, RETURNING RESULT 			ANALYTICS
					SETS FROM PROCEDURES
					
🔹 EXAMPLE TOGETHER: CURSOR VS COLLECTION

USING A CURSOR
---------------

DECLARE
  CURSOR C IS SELECT ENAME FROM EMP WHERE DEPTNO = 20;
  V_NAME EMP.ENAME%TYPE;
BEGIN
  OPEN C;
  LOOP
    FETCH C INTO V_NAME;
    EXIT WHEN C%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE('FROM CURSOR: ' || V_NAME);
  END LOOP;
  CLOSE C;
END;
/


USING A COLLECTION
-------------------

DECLARE
  TYPE T_NAMES IS TABLE OF EMP.ENAME%TYPE;
  V_NAMES T_NAMES;
BEGIN
  SELECT ENAME BULK COLLECT INTO V_NAMES FROM EMP WHERE DEPTNO = 20;

  FOR I IN 1 .. V_NAMES.COUNT LOOP
    DBMS_OUTPUT.PUT_LINE('FROM COLLECTION: ' || V_NAMES(I));
  END LOOP;
END;
/


👉 CURSOR FETCHES ROW BY ROW,
👉 COLLECTION FETCHES ALL ROWS AT ONCE AND PROCESSES IN MEMORY.

✅ IN SUMMARY:

USE CURSORS WHEN: YOU NEED ROW-BY-ROW CONTROL, DYNAMIC QUERIES, OR RETURNING A RESULT SET TO CLIENTS.

USE COLLECTIONS WHEN: YOU NEED BULK PROCESSING, IN-MEMORY STORAGE, OR PASSING LISTS/ARRAYS AROUND PROCEDURES.

---------COLLECTION-------------


Sl. No.   Name					Descriptions
1			count			Gives the number of elements present in the collection.
2			limit				Verifies the collection size.
3			exists(m)		Returns true if mth element present in the collection else returns false.
4			first				Gives start index number in collection with integer subscript.
5			last				Gives end index number in collection with integer subscript.
6			extend			Adds NULL element to the collection end.
7			next(m)			Gives the index that succeeds mth index.
8			prior(m)		Gives the index that precedes m index.
9			trim				Deletes an element from the end of collection.
10			trim(m)			Deletes m elements from the end of collection.
11			delete			Deletes all elements from collection, setting count to 0.
12			delete(m)		Deletes mth element from collection, if mth element is NULL, then no action is performed.
13			delete(m,k)	Deletes element from mth to kth position.
14			extend(m)		Adds m element to the collection end.
15			extend(m,k)	Adds m copies of the kth element to the end of collection.


Another difference between pls_integer and binary_integer is that when calculations involving a pls_integer overflow 
the PL/SQL engine will raise a run time exception. 
But, calculations involving a binary_integer will not raise an exception even if there is an overflow.



