1) Department Wise Avg, Max, Min Salary

SELECT MAX(SALARY) OVER (PARTITION BY DEPARTMENT_ID) MAX_SAL, 
TRUNC(AVG(SALARY) OVER (PARTITION BY DEPARTMENT_ID)) AVG_SAL,
MIN(SALARY) OVER (PARTITION BY DEPARTMENT_ID) MIN_SAL,
DEPARTMENT_ID, FIRST_NAME, SALARY FROM EMP ORDER BY DEPARTMENT_ID;

